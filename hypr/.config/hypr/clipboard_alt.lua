-- macOS-like clipboard on Alt (Alt acts like Command). Mirrors Omarchy's
-- default/hypr/bindings/clipboard.lua: terminals get Ctrl+Shift+C/V, other
-- windows get Ctrl+C/V.

local function send_shortcut_once(mods, key)
  return function()
    hl.dispatch(hl.dsp.send_key_state({ mods = mods, key = key, state = "down" }))
    hl.timer(function()
      hl.dispatch(hl.dsp.send_key_state({ mods = mods, key = key, state = "up" }))
    end, { timeout = 50, type = "oneshot" })
  end
end

local function active_window_is_terminal()
  local window = hl.get_active_window()
  if not window then
    return false
  end

  for _, tag in ipairs(window.tags or {}) do
    if tag:gsub("%*$", "") == "terminal" then
      return true
    end
  end

  return false
end

local function universal(default_mods, default_key, terminal_mods, terminal_key)
  return function()
    if active_window_is_terminal() then
      send_shortcut_once(terminal_mods, terminal_key)()
    else
      send_shortcut_once(default_mods, default_key)()
    end
  end
end

o.bind("ALT + C", "Copy", universal("CTRL", "C", "CTRL SHIFT", "C"))
o.bind("ALT + V", "Paste", universal("CTRL", "V", "CTRL SHIFT", "V"))
